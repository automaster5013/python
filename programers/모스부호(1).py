def solution(letter):
    morse_sign = [".-","-...","-.-.","-..",".","..-.","--.","....",
    "..",".---","-.-",".-..","--","-.","---",".--.","--.-",".-.","...",
    "-","..-","...-",".--","-..-","-.--","--.."]

    answer = ''
    for code in letter.split():
        idx = morse_sign.index(code)
        answer += chr(ord('a') + idx)
        
    return answer

