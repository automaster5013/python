n = int(input())
buffer = ""

for i in range(1, n + 1):
    # 현재 행의 숫자를 n번 나열하고 줄바꿈 추가
    line = (str(i) + " ") * n
    buffer += line.strip() + "\n"

print(buffer, end="")

