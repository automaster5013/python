n = int(input())

for i in range(1, n + 1):
    # [i, i, i, ...] 리스트 생성
    row = [i for _ in range(n)]
    # * 연산자는 리스트 내부 요소를 공백으로 구분해 출력해줍니다.
    print(*row)

