n = int(input())

for i in range(1, n + 1):
    # 숫자 뒤에 공백을 붙여 문자열을 만든 뒤 n번 반복
    row = (str(i) + " ") * n
    print(row.strip()) # 마지막 불필요한 공백 제거 후 출력

